"""Independent exact-rational oracle for the explicitly selected visual model."""
from fractions import Fraction as F
from pathlib import Path
import json
D=Path(__file__).resolve().parent

def nearest(x): return (x+F(1,2)).numerator//(x+F(1,2)).denominator

def packed(c,fmt):
    if fmt: return sum(v<<(24-i*8) for i,v in enumerate(c))
    return sum((v>>4)<<(12-i*4) for i,v in enumerate(c))

def expanded(v,fmt):
    return [(v>>((3-i)*(8 if fmt else 4)) & (255 if fmt else 15))*(1 if fmt else 17) for i in range(4)]

def model(s,d,k,fmt):
    S,T=expanded(s,fmt),expanded(d,fmt)
    a=nearest(F(S[3]*k,255))
    C=[nearest(F(S[i]*a+T[i]*(255-a),255)) for i in range(3)]
    C.append(nearest(F(a)+F(T[3]*(255-a),255)))
    if fmt: return packed(C,fmt)
    return sum(nearest(F(v,17))<<((3-i)*4) for i,v in enumerate(C))

vectors=[]
for fmt in [0,1]:
    for As in [0,1,127,254,255]:
        for K in [0,1,127,254,255]:
            for Ad in [0,1,127,254,255]:
                s=packed([253,91,17,As],fmt);d=packed([3,171,239,Ad],fmt)
                vectors.append(dict(fmt=fmt,As=As,K=K,Ad=Ad,source=s,destination=d,expected=model(s,d,K,fmt)))
(D/'expected-vectors.json').write_text(json.dumps(vectors,indent=2)+'\n')
lines=['/* Generated by exact-rational make_vectors.py, not backend code. */',
       'struct vector {unsigned fmt,as,k,ad;uint32_t src,dst,out;};','static const struct vector vectors[]={']
for v in vectors:
    lines.append(' {%d,%d,%d,%d,0x%xU,0x%xU,0x%xU},'%tuple(v.values()))
lines.append('};')
(D/'expected-vectors.h').write_text('\n'.join(lines)+'\n')
