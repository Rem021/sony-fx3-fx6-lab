#!/usr/bin/env python3
"""Reject observed magic only after bounded Zstandard structure validation."""
import hashlib,json
from pathlib import Path
HERE=Path(__file__).resolve().parent
def main():
    target=HERE/'zstd-candidate-results.json';assert not target.exists()
    raw=(HERE/'outer-members/VENICE/DATA23213').read_bytes()
    assert hashlib.sha256(raw).hexdigest()=='93d01601322e3d1931a76b1c6f4f3bfdfb9a0745cfc0ec4eecb253c694b30d5c'
    probes=json.loads((HERE/'payload-structure-results.json').read_text());positions=probes['signatures']['zstd'];assert len(positions)==1
    rows=[]
    for at in positions:
        b=raw[at:at+32];assert b[:4]==b'\x28\xb5\x2f\xfd'
        descriptor=b[4];assert descriptor&8==0 and descriptor&32
        cursor=5;did_bytes=[0,1,2,4][descriptor&3];did=int.from_bytes(b[cursor:cursor+did_bytes],'little');cursor+=did_bytes
        fcs_bytes=[1,2,4,8][descriptor>>6];content_size=int.from_bytes(b[cursor:cursor+fcs_bytes],'little')+(256 if fcs_bytes==2 else 0);cursor+=fcs_bytes
        header=int.from_bytes(b[cursor:cursor+3],'little');kind=(header>>1)&3;size=header>>3;maximum=min(content_size,128*1024)
        assert kind==1 and size>maximum
        rows.append(dict(offset=at,first32_hex=b.hex(),descriptor=hex(descriptor),unused_bit_set=bool(descriptor&16),
            unused_bit_is_not_rejection_reason=True,reserved_bit_set=False,single_segment=True,dictionary_ID=did,
            frame_content_size=content_size,first_block_header_offset=at+cursor,first_block_type='RLE',
            first_block_regenerated_bytes=size,block_maximum_size=maximum,valid_frame=False,
            rejection='First RLE block regenerated size exceeds min(Window_Size,128KiB); for Single_Segment,Window_Size=Frame_Content_Size.'))
    out=dict(candidates=rows,format_reference='https://raw.githubusercontent.com/facebook/zstd/dev/doc/zstd_compression_format.md',
        specification_version='0.4.5',checks=['Single_Segment determines window size','RLE Block_Size is regenerated byte count','Block regenerated size cannot exceed Block_Maximum_Size'],
        scope='Bounded frame and first-block structure rejection; no zstd library installed and no payload or firmware executed. Magic hit remains recorded in original probe.')
    target.write_text(json.dumps(out,indent=2)+'\n');print(json.dumps(dict(zstd_magic_candidates=len(rows),structurally_valid_frames=0,rejection=rows[0]['rejection'])))
if __name__=='__main__':main()
